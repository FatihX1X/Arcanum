const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const outputPath = path.join(root, 'packages', 'sdk', 'src', 'generated', 'contracts.ts');
const deploymentPath = path.join(root, 'deployments', 'arcMainnet.json');
const contracts = {
  messenger: 'ArcanumMessenger',
  agents: 'ArcanumAgents',
  groups: 'ArcanumGroups',
  bulkSender: 'ArcanumBulkSender',
  gigBoard: 'ArcanumGigBoard',
  escrow: 'ArcanumEscrow',
};

function artifactPath(name) {
  return path.join(root, 'artifacts', 'contracts', `${name}.sol`, `${name}.json`);
}

function render() {
  const deployment = JSON.parse(fs.readFileSync(deploymentPath, 'utf8'));
  const lines = [
    '// This file is generated by scripts/generate-sdk-contracts.js. Do not edit by hand.',
    "import type { Abi, Address } from 'viem';",
    '',
    `export const ARC_MAINNET_CHAIN_ID = ${deployment.chainId} as const;`,
    "export const ARC_MAINNET_RPC_URL = 'https://rpc.mainnet.arc.io' as const;",
    "export const ARC_MAINNET_EXPLORER_URL = 'https://explorer.arc.io' as const;",
    '',
  ];

  for (const [key, name] of Object.entries(contracts)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath(name), 'utf8'));
    lines.push(`export const ${key}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const satisfies Abi;`, '');
  }

  lines.push(
    'export const arcMainnetDeployments = {',
    `  chainId: ${deployment.chainId},`,
    ...Object.keys(contracts).map((key) => `  ${key}: { address: '${deployment[key].address}' as Address, blockNumber: ${deployment[key].blockNumber}n },`),
    '} as const;',
    '',
    'export const arcanumContracts = {',
    ...Object.keys(contracts).map((key) => `  ${key}: { ...arcMainnetDeployments.${key}, abi: ${key}Abi },`),
    '} as const;',
    '',
  );

  return `${lines.join('\n')}\n`;
}

const expected = render();
if (process.argv.includes('--check')) {
  const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (actual !== expected) {
    console.error('SDK contract bindings are stale. Run npm run sdk:generate.');
    process.exitCode = 1;
  } else {
    console.log('SDK contract bindings match Hardhat artifacts and the mainnet manifest.');
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, expected);
  console.log(`Generated ${path.relative(root, outputPath)}.`);
}
